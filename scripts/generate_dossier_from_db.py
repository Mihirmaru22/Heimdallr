    lines.append("")
    lines.append("#### Disambiguation Tasks Automatically Injected:")
    lines.append("1. **Task ID `tsk_74da8dcb` (Priority 10)**: `Disambiguate: Locate the primary U.S. bankruptcy court docket or filing record for Canoo Inc. to confirm the exact filing date.`")
    lines.append("2. **Task ID `tsk_72cf1e66` (Priority 10)**: `Disambiguate: Collect at least two independent reputable news reports or official company statements confirming the January 21, 2025 bankruptcy filing date.`")
