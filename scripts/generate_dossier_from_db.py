    lines.append("")
    lines.append("| Priority | Task Title | Target Research Focus |")
    lines.append("| :---: | :--- | :--- |")
    for t in tasks:
        if t["status"] == "ready":
            lines.append(f"| **P{t['priority']}** | {t['title']} | {t['description'][:110]}... |")
