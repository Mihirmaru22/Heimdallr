    lines.append("")

    # Section 8
    lines.append("## 8. Resource Telemetry & Free-Tier Quota Efficiency")
    lines.append("")
    lines.append("This entire investigation was executed using the **Category 1 free model tier** (`qwen/qwen3.8-27b:free`) through OpenRouter, backed by the user's $10 top-up allowance (1,000 requests/day):")
    lines.append("")
    lines.append("| Parameter | Incurred / Measured Value | Constraint / Boundary |")
    lines.append("| :--- | :--- | :--- |")
    lines.append("| **LLM Model Employed** | `qwen/qwen3.8-27b:free` | OpenRouter Category 1 Free Tier |")
