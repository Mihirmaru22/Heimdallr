    lines.append("## 7. Provenance, Evidence Passages, & Source Registry")
    lines.append("")
    lines.append("All claims are backed by immutable document records stored in SQLite:")
    lines.append("")
    lines.append("| Document ID | Ingested Title | Source URL | Ingested Bytes | Fetch Method | Fetch Timestamp |")
    lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
    for d in documents:
        lines.append(f"| `{d['document_id']}` | {d['title']} | [{d['url']}]({d['url']}) | {len(d['text_content']):,} bytes | `{d['fetch_method']}` | `{d['fetched_at']}` |")
    lines.append("")

    lines.append("### Key Evidence Excerpts")
    lines.append("")
    lines.append("1. **Automotive Manufacturers Overview** (`doc_a86a7035`):")
    lines.append("   > *\"The currently active brands from the 'Big Three' manufacturers (Ford, General Motors and Stellantis) are shown below... Buick Founded in 1899 as 'Buick Auto-Vim and Power Company' and acquired by General Motors in 1908...\"*")
    lines.append("")
