// Precomputes which country each globe dot falls in, plus simplified border and coast lines, so the
// browser does not ship the full world map or rasterise it on every load. Run after changing the dot
// count, the tolerance or the map data:
//   node scripts/build-earth.mjs
// Countries come from Natural Earth via world-atlas (public domain data, ISC package).
import { readFileSync, writeFileSync } from "node:fs";
import { feature, mesh } from "topojson-client";

const COUNT = 64000;
// Lines keep a point only when it is at least this many degrees from the last one kept.
const TOLERANCE = 0.4;
const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url)));
const fc = feature(topo, topo.objects.countries);

// Each country as rings of [lon, lat] with a bounding box, for an even-odd point-in-polygon test.
const countries = fc.features.map((f) => {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.flat();
  let minX = 180, maxX = -180, minY = 90, maxY = -90;
  for (const r of rings) for (const [x, y] of r) {
    minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
  const id = Number(f.id);
  return { id: Number.isFinite(id) ? id : -1, rings, box: [minX, minY, maxX, maxY] };
});

function inside(lon, lat, rings) {
  let hit = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i], [xj, yj] = ring[j];
      // Skip edges that jump across the antimeridian; they are not real borders.
      if (Math.abs(xi - xj) > 180) continue;
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

// The same Fibonacci sphere as src/geo/earth.ts, and the same inverse of latLonToXYZ.
const golden = Math.PI * (3 - Math.sqrt(5));
const out = new Uint8Array(COUNT).fill(255);
for (let i = 0; i < COUNT; i++) {
  const y = 1 - (i / (COUNT - 1)) * 2;
  const r = Math.sqrt(1 - y * y);
  const x = Math.cos(golden * i) * r, z = Math.sin(golden * i) * r;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = (Math.atan2(z, -x) * 180) / Math.PI - 180;
  if (lon < -180) lon += 360;
  for (let c = 0; c < countries.length; c++) {
    const [a, b, d, e] = countries[c].box;
    if (lon >= a && lon <= d && lat >= b && lat <= e && inside(lon, lat, countries[c].rings)) { out[i] = c; break; }
  }
}
const land = out.filter((v) => v !== 255).length;

// Border and coast lines, delta-encoded in tenths of a degree so they compress well: a -128 byte starts a
// line and is followed by its first point as two little-endian int16 (lat, lon); every other byte pair is
// an int8 step (dlat, dlon) from the previous point.
function lines(geom) {
  const bytes = [];
  let points = 0;
  const i16 = (v) => { bytes.push(v & 255, (v >> 8) & 255); };
  for (const line of geom.coordinates) {
    const kept = [line[0]];
    for (let i = 1; i < line.length; i++) {
      const [x, y] = line[i], [px, py] = kept[kept.length - 1];
      if (i === line.length - 1 || Math.hypot(x - px, y - py) >= TOLERANCE) kept.push(line[i]);
    }
    if (kept.length < 2) continue;
    let [lon, lat] = kept[0].map((v) => Math.round(v * 10));
    bytes.push(128); i16(lat); i16(lon);
    for (const [x, y] of kept.slice(1)) {
      const tlat = Math.round(y * 10), tlon = Math.round(x * 10);
      // Long steps are split so each fits in an int8.
      const n = Math.max(1, Math.ceil(Math.max(Math.abs(tlat - lat), Math.abs(tlon - lon)) / 127));
      for (let k = 1; k <= n; k++) {
        const nlat = Math.round(lat + ((tlat - lat) * k) / n), nlon = Math.round(lon + ((tlon - lon) * k) / n);
        bytes.push((nlat - lat) & 255, (nlon - lon) & 255);
        lat = nlat; lon = nlon;
      }
    }
    points += kept.length;
  }
  return { b64: Buffer.from(bytes).toString("base64"), points };
}
const borders = lines(mesh(topo, topo.objects.countries, (a, b) => a !== b));
const coast = lines(mesh(topo, topo.objects.countries, (a, b) => a === b));
writeFileSync(new URL("../src/geo/earth-data.ts", import.meta.url), `// Generated by scripts/build-earth.mjs from Natural Earth (world-atlas countries-50m). Do not edit.
// DOTS: one byte per globe dot (${COUNT} dots), the index into IDS of the country it falls in, 255 for ocean.
export const COUNT = ${COUNT};
export const IDS = [${countries.map((c) => c.id).join(",")}];
export const DOTS = "${Buffer.from(out).toString("base64")}";
// BORDERS and COAST: delta-encoded lines, see lines() in scripts/build-earth.mjs.
export const BORDERS = "${borders.b64}";
export const COAST = "${coast.b64}";
`);
console.log(`${land} land dots of ${COUNT}, ${countries.length} countries, ${borders.points} border and ${coast.points} coast points`);
